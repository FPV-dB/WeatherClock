// Builds the compressed (gzip) panel from web/index.html into web/out/panel-<hash>.html.gz (it goes to the
// site and from there into the clock's file storage) and weatherclock/web.h with the loader and the hash.
// O navegador descompacta sozinho (Content-Encoding: gzip). ~70 KB viram ~19 KB.
// Edit web/index.html (Portuguese and Spanish texts: web/i18n.json) and run this script
// (sim/build.sh already runs it). With terser installed (npm install in web/), the JavaScript is minified.
//
// The Portuguese/Spanish dictionary doesn't go in flash: the panel fetches panel/i18n-<code>.json from the site
// (the code is a hash of web/i18n.json, substituted for __I18V__) and stores it in the browser.
// The share card (web/share.js) likewise, as panel/share-<code>.js, downloaded only when sharing.
// With each version, publish the files in web/out/ to the site's panel/ folder (gh-pages).
const fs = require('fs'), path = require('path'), zlib = require('zlib'), crypto = require('crypto');
const src = path.join(__dirname, 'index.html');
const out = path.join(__dirname, '..', 'weatherclock', 'web.h');

(async () => {
  let html = fs.readFileSync(src, 'utf8');
  const dict = fs.readFileSync(path.join(__dirname, 'i18n.json'));
  const ver = crypto.createHash('sha1').update(dict).digest('hex').slice(0, 10);
  html = html.replace(/__I18V__/g, ver).replace(/__I18I__/g, 'sha384-' + crypto.createHash('sha384').update(dict).digest('base64'));
  fs.mkdirSync(path.join(__dirname, 'out'), { recursive: true });
  fs.writeFileSync(path.join(__dirname, 'out', `i18n-${ver}.json`), dict);
  // time zones (web/tz.json, generated by web/tzgen.sh from tzdata): likewise, panel/tz-<code>.json with SRI, downloaded only
  // when the user picks the city (the clock receives the ready-made POSIX rule)
  const tz = fs.readFileSync(path.join(__dirname, 'tz.json'));
  const tzv = crypto.createHash('sha1').update(tz).digest('hex').slice(0, 10);
  html = html.replace(/__TZV__/g, tzv).replace(/__TZI__/g, 'sha384-' + crypto.createHash('sha384').update(tz).digest('base64'));
  fs.writeFileSync(path.join(__dirname, 'out', `tz-${tzv}.json`), tz);
  // share card: web/share.js goes to the site as panel/share-<code>.js (minified, if possible)
  let share = fs.readFileSync(path.join(__dirname, 'share.js'), 'utf8');
  const shv = crypto.createHash('sha1').update(share).digest('hex').slice(0, 10);
  html = html.replace(/__SHV__/g, shv);

  // JavaScript minified by terser, if installed (only renames what's local: the HTML calls global functions)
  const a = html.indexOf('<script>') + 8, b = html.indexOf('</script>');
  let terser = null;
  try { terser = require('terser'); } catch (e) { console.log('warning: without terser (npm install in web/), the panel is ~1 KB bigger'); }
  if (terser) share = (await terser.minify(share, { compress: { passes: 2 }, format: { comments: false } })).code;
  fs.writeFileSync(path.join(__dirname, 'out', `share-${shv}.js`), share);
  // SRI of the published file (already minified): the browser refuses to run it if the site serves anything else
  html = html.replace(/__SHI__/g, 'sha384-' + crypto.createHash('sha384').update(share).digest('base64'));
  if (terser) html = html.slice(0, a) + (await terser.minify(html.slice(a, b), { compress: { passes: 2 }, format: { comments: false } })).code + html.slice(b);

  // strips what the browser doesn't use before compressing: whole-line comments (HTML and JS) and indentation
  const min = html.replace(/<!--[\s\S]*?-->/g, '').split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('//')).join('\n');
  const gzip = s => {
    const g = zlib.gzipSync(s, { level: 9 });
    g[4] = g[5] = g[6] = g[7] = 0;  // zeroes the time in the gzip header: same HTML -> same file
    return g;
  };
  const gz = gzip(min);
  // From 1.19 the panel isn't in program flash: it lives in the clock's file storage as
  // /www/<hash>.gz. The site publishes panel/panel-<hash>.html.gz (never overwrite: each firmware asks for its own)
  // and the firmware only serves the file whose SHA-256 matches the PANEL_HASH below.
  const sha = crypto.createHash('sha256').update(gz);
  const hash = sha.copy().digest('hex').slice(0, 24), sri = 'sha256-' + sha.digest('base64');
  const file = `panel-${hash}.html.gz`;
  fs.writeFileSync(path.join(__dirname, 'out', file), gz);
  // minimal loader (web/loader.html), this one in flash: installs the panel the first time
  const loader = gzip(fs.readFileSync(path.join(__dirname, 'loader.html'), 'utf8').replace(/<!--[\s\S]*?-->/g, '')
    .replace(/__PANEL_FILE__/g, file).replace(/__PANEL_SRI__/g, sri).split('\n').map(l => l.trim()).filter(l => l).join('\n'));
  let h = '// Generated by web/build.js from web/index.html and web/loader.html — do not edit by hand.\n';
  h += '#pragma once\n#include <pgmspace.h>\n\n';
  h += `// this version's panel: ${file} (${gz.length} bytes), SRI ${sri}\n`;
  // Node's gzip (zlib with CPU optimisations) may give different bytes on another machine with the same
  // content; this line only depends on the content and is what the GitHub automatic build compares
  h += `// panel content before gzip: sha256 ${crypto.createHash('sha256').update(min).digest('hex')}\n`;
  h += `#define PANEL_HASH "${hash}"  // first 24 hex of the SHA-256: the file name in /www\n`;
  h += `static const uint8_t LOADER_HTML_GZ[${loader.length}] PROGMEM = {`;
  for (let i = 0; i < loader.length; i++) h += (i % 24 ? '' : '\n  ') + '0x' + loader[i].toString(16).padStart(2, '0') + ',';
  h += '\n};\n';
  fs.writeFileSync(out, h);
  // for latest.json and tools/release.sh ("site": the files that go to panel/ on the site)
  fs.writeFileSync(path.join(__dirname, 'out', 'panel.json'), JSON.stringify({ panel: file, psri: sri, psize: gz.length,
    site: [file, `i18n-${ver}.json`, `tz-${tzv}.json`, `share-${shv}.js`] }) + '\n');
  console.log(`panel: ${(fs.statSync(src).size / 1024).toFixed(1)} KB -> ${(gz.length / 1024).toFixed(1)} KB (gzip) in ${file}; loader in flash: ${loader.length} bytes; dictionary i18n-${ver}.json, time zones tz-${tzv}.json, card share-${shv}.js`);
})();
