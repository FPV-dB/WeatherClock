#!/usr/bin/env node
// Update signatures for the Weather Clock (RSA-2048, PKCS#1 v1.5, SHA-256).
//
// The signature NEVER goes inside the firmware: it is a separate file (<file>.sig, 256 bytes) and the clock
// receives it in the X-Firmware-Sig header. In 1.20.0 it went at the end of the .bin.gz and the eboot used the last 4 bytes
// as the image size, erasing the boot loader (docs/SIGNATURES.md).
//
//   node scripts/sign.cjs key                creates the key pair (once; the private key stays OUTSIDE the repository)
//   node scripts/sign.cjs header             gera weatherclock/ota_key.h a partir de ota-public.pem
//   node scripts/sign.cjs sign <files>       creates <file>.sig for each one (needs the private key)
//   node scripts/sign.cjs verify <files>     checks <file> against <file>.sig with the public key
//
// Private key: SMALLTV_SIGNING_KEY or ~/.weatherclock/ota-private.pem.
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const pubPath = path.join(root, 'weatherclock/ota-public.pem');
const privPath = () => process.env.SMALLTV_SIGNING_KEY || path.join(os.homedir(), '.weatherclock', 'ota-private.pem');

function rsa2048(k) {
  if (k.asymmetricKeyType !== 'rsa' || k.asymmetricKeyDetails.modulusLength !== 2048) throw Error('the key must be 2048-bit RSA');
  return k;
}
const publicKey = () => rsa2048(crypto.createPublicKey(fs.readFileSync(pubPath)));
const keyId = k => crypto.createHash('sha256').update(k.export({ type: 'spki', format: 'der' })).digest('hex').slice(0, 16);
// Modulus (256 bytes) and exponent, big-endian, as br_rsa_public_key expects.
function rawKey(k = publicKey()) {
  const j = k.export({ format: 'jwk' });
  return { n: Buffer.from(j.n, 'base64url'), e: Buffer.from(j.e, 'base64url') };
}

function sign(data, priv) {
  return crypto.sign('sha256', data, { key: priv, padding: crypto.constants.RSA_PKCS1_PADDING });
}
function verify(data, sig, pub = publicKey()) {
  return sig.length === 256 && crypto.verify('sha256', data, { key: pub, padding: crypto.constants.RSA_PKCS1_PADDING }, sig);
}

function main(cmd, files) {
  if (cmd === 'key' || cmd === 'chave') {
    const p = privPath();
    if (fs.existsSync(p) || fs.existsSync(pubPath)) throw Error('a key already exists (' + (fs.existsSync(p) ? p : pubPath) + '): do not replace it without planning for the installed clocks');
    const { publicKey: pub, privateKey } = crypto.generateKeyPairSync('rsa', { modulusLength: 2048 });
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
    fs.writeFileSync(pubPath, pub.export({ type: 'spki', format: 'pem' }));
    console.log('private key: ' + p + '\npublic key: ' + pubPath + '\nid: ' + keyId(pub) + '\nKEEP A COPY OF THE PRIVATE KEY: without it you cannot sign updates for the clocks that trust this key.');
  } else if (cmd === 'header') {
    // As bytes (modulus and exponent), so the firmware can use BearSSL's RSA maths without the PEM reader.
    const { n, e } = rawKey(), hex = b => [...b].map(x => '0x' + x.toString(16).padStart(2, '0'));
    const rows = a => a.join(',').match(/(0x..,?){1,16}/g).join('\n  ');
    fs.writeFileSync(path.join(root, 'weatherclock/ota_key.h'),
      '// Generated by scripts/sign.cjs from ota-public.pem (the PUBLIC key only). Do not edit by hand.\n' +
      '// id ' + keyId(publicKey()) + '\n#pragma once\n#include <pgmspace.h>\n' +
      'static const uint8_t OTA_KEY_N[' + n.length + '] PROGMEM = {\n  ' + rows(hex(n)) + '};\n' +
      'static const uint8_t OTA_KEY_E[' + e.length + '] PROGMEM = {' + hex(e).join(',') + '};\n');
    console.log('ota_key.h gerado (id ' + keyId(publicKey()) + ')');
  } else if (cmd === 'sign') {
    if (!files.length) throw Error('informe os arquivos');
    const p = privPath();
    if (!fs.existsSync(p)) throw Error('private key not found at ' + p + ' (set SMALLTV_SIGNING_KEY)');
    const priv = crypto.createPrivateKey(fs.readFileSync(p));
    if (keyId(rsa2048(crypto.createPublicKey(priv))) !== keyId(publicKey())) throw Error("the private key doesn't match the firmware's ota-public.pem");
    for (const f of files) {
      const data = fs.readFileSync(f), sig = sign(data, priv);
      if (!verify(data, sig)) throw Error(f + ': the generated signature does not verify');
      fs.writeFileSync(f + '.sig', sig);
      console.log(path.basename(f) + '.sig: assinatura conferida');
    }
  } else if (cmd === 'verify') {
    if (!files.length) throw Error('informe os arquivos');
    for (const f of files) {
      if (!verify(fs.readFileSync(f), fs.readFileSync(f + '.sig'))) throw Error(path.basename(f) + ': invalid signature');
      console.log(path.basename(f) + ': assinatura OK');
    }
  } else {
    throw Error('usage: node scripts/sign.cjs key|header|sign|verify [files]');
  }
}

if (require.main === module) {
  try { main(process.argv[2], process.argv.slice(3)); } catch (e) { console.error('ERRO: ' + e.message); process.exitCode = 1; }
}
module.exports = { sign, verify, keyId, publicKey, rawKey };
