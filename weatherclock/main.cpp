bool endsWithIgnoreCase(const String &s, const char *suffix) {
  size_t n = s.length(), m = strlen(suffix);
  if (m > n) return false;
  for (size_t i = 0; i < m; i++) {
    char a = s[n - m + i];
    if (a >= 'A' && a <= 'Z') a += 'a' - 'A';
    if (a != suffix[i]) return false;
  }
  return true;
}
bool isGif(const String &n) { return endsWithIgnoreCase(n, ".gif"); }
bool isJpg(const String &n) { return endsWithIgnoreCase(n, ".jpg") || endsWithIgnoreCase(n, ".jpeg"); }
// weatherbox: animation already in pixels (.wcr, made by the radar program). Header "WCR1", width and height
// (u16), frames (u8), 1 spare byte and each frame's delay in ms (u16); then, per frame, the size (u32)
// and pairs (repeats u8, RGB565 colour u16). Goes from the file to the screen row by row: ~1 KB of RAM, without the
// GIF decoder (24 KB), so it doesn't depend on memory being in one piece.
bool isWcr(const String &n) { return endsWithIgnoreCase(n, ".wcr"); }

