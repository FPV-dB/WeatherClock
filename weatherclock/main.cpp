// HTTP/1.0 GET (reply without "chunked", closes at the end) instead of HTTPClient (~4 KB).
// Returns the HTTP code (negative if it can't connect) and leaves the client at the start of the body.
static bool httpLine(WiFiClient &c, String &line, uint32_t start, uint16_t timeoutMs) {
  line = "";
  while (millis() - start < timeoutMs) {
    if (c.available()) {
      int ch = c.read();
      if (ch == '\n') return true;
      if (ch < 0) continue;
      if (line.length() >= 512) return false;
      line += (char)ch;
    } else if (!c.connected()) return false;
    else delay(1);
  }
  return false;
}

// Appends a decimal already bounded by the firmware without creating another String on the heap.
static void appendFixed(String &out, float value, uint8_t digits) {
  bool neg = value < 0;
  if (neg) value = -value;
  uint32_t scale = 1;
  for (uint8_t i = 0; i < digits; i++) scale *= 10;
  uint32_t scaled = lroundf(value * scale);
  if (neg && scaled) out += '-';
  out += scaled / scale;
  if (!digits) return;
  out += '.';
  uint32_t frac = scaled % scale;
  for (uint32_t div = scale / 10; div; div /= 10) out += (char)('0' + frac / div % 10);
}

uint32_t httpDateEpoch = 0;  // Date header of the last reply (0 = there wasn't one)

int httpGet(WiFiClient &c, const String &url, uint16_t timeoutMs) {
  httpDateEpoch = 0;
  if (!safeHttpUrl(url.c_str(), url.length())) return -1;
  int end = 7;
  while (end < (int)url.length() && url[end] != '/' && url[end] != '?') end++;
  String host = url.substring(7, end), path = url.substring(end);
  if (!path.length() || path[0] == '?') path = "/" + path;
  uint16_t port = 80;
  int colon = host.indexOf(':');
  if (colon >= 0) {
    port = host.substring(colon + 1).toInt();
    host.remove(colon);
  }
  c.setTimeout(timeoutMs);
  if (!host.length() || !port || !c.connect(host.c_str(), port)) return -1;
  // Sends in parts: concatenating everything created a big temporary String on every request.
  c.print(F("GET "));
  c.print(path);
  c.print(F(" HTTP/1.0\r\nHost: "));
  c.print(host);
  c.print(F("\r\nUser-Agent: WeatherClock\r\nConnection: close\r\n\r\n"));
  uint32_t start = millis();
  String line;
  line.reserve(128);  // httpLine reuses the same capacity for the status and headers
  if (!httpLine(c, line, start, timeoutMs)) return -2;
  int sp = line.indexOf(' ');
  int code = sp > 0 ? line.substring(sp + 1).toInt() : 0;
  if (code <= 0) return -2;
  size_t total = line.length();
  for (int headers = 0; headers < 48; headers++) {
    if (!httpLine(c, line, start, timeoutMs)) return -2;
    total += line.length();
    if (total > 8192) return -2;
    if (line.length() <= 1) return code;
    if (!strncasecmp_P(line.c_str(), PSTR("date:"), 5)) {
      int64_t d = httpDateToEpoch(line.c_str() + 5);
      if (d > 0) httpDateEpoch = (uint32_t)d;
    }
  }
  return -2;
}

