const char *MEDIA_DIRS[] = {"/image", "/gif"};

uint32_t fsInfoAt = 0;  // when the free space was measured for the panel (0 = measure again)

void rebuildAlbum() {
  fsInfoAt = 0;  // photos uploaded, deleted or formatted: the free space changed
  album.clear();
  if (!fsOk) return;
  for (const char *dir : MEDIA_DIRS) {
    Dir d = LittleFS.openDir(dir);
    while (d.next()) {
      if (d.isDirectory()) continue;
      String n = String(dir) + "/" + d.fileName();
      // the original firmware's boot animation doesn't go in the album
      if ((isJpg(n) || isGif(n) || isWcr(n)) && d.fileName() != "boot.gif" && d.fileName() != "boot.jpg") album.push_back(n);
    }
  }
}

