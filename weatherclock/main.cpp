// Every phase that starts gets a number (phaseSeq); when the screen finishes drawing it, with the numbers,
// shownSeq becomes that number. The panel waits for both to match before showing the countdown: it never starts
// before the clock (see "pseq"/"pshown" in /api/state).
uint16_t phaseSeq = 0, shownSeq = 0;

void startPhase(Phase p, bool run) {
  phase = p;
  totalMs = remainingMs = (uint32_t)phaseMinutes(p) * 60000UL;
  running = run;
  lastTick = millis();
  phaseSeq++;
}

