// ---------- protection against Wi-Fi downgrade (CVE-2020-12638) ----------
// A fake beacon with the privacy bit off, together with a channel-switch announcement, makes the ESP8266
// SDK start talking WITHOUT encryption to the access point of whoever is nearby. Espressif
// didn't fix this in the Arduino core's NONOS SDK; the known workaround is to watch for a change
// in the authentication mode and reconnect when it weakens. reconnect() keeps the saved network
// (disconnect() would erase the password) and the new connection only accepts WPA or better.
WiFiEventHandler wifiAuthHandler;
volatile bool wifiDowngrade = false;

static int authRank(uint8_t m) { return m == AUTH_OPEN ? 0 : m == AUTH_WEP ? 1 : 2; }  // WPA, WPA2 and mixed: 2

// A network saved by another firmware (the original) may not require WPA: now it does, as the core's begin() does
// returns true if it had to change the saved network
bool wifiHarden() {
  struct station_config conf;
  if (!wifi_station_get_config_default(&conf) || !conf.password[0]) return false;  // open network saved: nothing to require
  bool ok = conf.threshold.authmode >= AUTH_WPA_PSK;  // NONOS 2.2: only connects to networks with this mode or better
#if (NONOSDK >= (0x30000))
  ok = ok && conf.open_and_wep_mode_disable;
  conf.open_and_wep_mode_disable = 1;
#endif
  if (ok) return false;
  conf.threshold.authmode = AUTH_WPA_PSK;
  wifi_station_set_config(&conf);
  return true;
}

void wifiGuardBegin() {
  wifiAuthHandler = WiFi.onStationModeAuthModeChanged([](const WiFiEventStationModeAuthModeChanged &e) {
    if (authRank(e.newMode) < authRank(e.oldMode)) wifiDowngrade = true;  // handled in the loop, outside the SDK
  });
}

// Connection with a fixed channel and BSSID (see connectStored): if it drops and doesn't come back soon (the router changed channel or, on a
// mesh network, the access point is another one), go back to the saved network without pinning anything.
bool wifiPinned = false;
uint32_t wifiLostAt = 0;

void wifiUnpin() {
  String ssid = WiFi.SSID(), psk = WiFi.psk();
  WiFi.persistent(false);
  WiFi.begin(ssid.c_str(), psk.c_str());
  WiFi.persistent(true);
  wifiPinned = false;
}

void wifiGuardLoop() {
  if (wifiPinned) {
    if (WiFi.status() == WL_CONNECTED) wifiLostAt = 0;
    else if (!wifiLostAt) wifiLostAt = millis() | 1;
    else if (millis() - wifiLostAt > 15000) wifiUnpin();
  }
  if (!wifiDowngrade) return;
  wifiDowngrade = false;
  wifiDowngrades++;
  WiFi.reconnect();
}

static uint32_t ssidHash(const String &s) {  // FNV-1a
  uint32_t h = 2166136261u;
  for (char c : s) h = (h ^ (uint8_t)c) * 16777619u;
  return h;
}

// Waits to connect while animating the start-up screen bar (see bootAnim)
static bool waitWifi(uint32_t ms) {
  uint32_t t0 = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - t0 < ms) {
    bootAnim(0);
    delay(30);
  }
  return WiFi.status() == WL_CONNECTED;
}

// Network saved in the SDK. With the last router's channel and BSSID (EEPROM, see wifiHintSave) the SDK doesn't scan the 13
// channels: it connects directly. RAM only (persistent off): the pinned BSSID doesn't go to flash, which keeps the usual
// network. If it doesn't connect within a few seconds, it falls back to the full scan.
bool connectStored(uint32_t timeoutMs) {
  uint32_t t0 = millis();
  WiFi.mode(WIFI_STA);
  WiFi.hostname(netName);
  bool hardened = wifiHarden();
  if (!hardened && WiFi.status() == WL_CONNECTED) {  // the SDK connected by itself while the screen was starting
    bootWifiPath = 2;
    return true;
  }
  WifiHint h;
  EEPROM.get(WIFIH_OFF, h);
  String ssid = WiFi.SSID(), psk = WiFi.psk();
  if (!ssid.length() || h.magic != WIFI_MAGIC || h.ssid != ssidHash(ssid) || h.chan < 1 || h.chan > 13) {
    WiFi.begin();
    return waitWifi(timeoutMs);
  }
  WiFi.persistent(false);
  WiFi.begin(ssid.c_str(), psk.c_str(), h.chan, h.bssid);
  bool ok = waitWifi(min<uint32_t>(4000, timeoutMs));
  if (ok) {
    bootWifiPath = 1;
    wifiPinned = true;
  } else {
    bootWifiPath = 3;
    WiFi.begin(ssid.c_str(), psk.c_str());
    uint32_t used = millis() - t0;
    ok = waitWifi(used < timeoutMs ? timeoutMs - used : 0);
  }
  WiFi.persistent(true);
  return ok;
}

// Stores the current router's channel and BSSID; only writes flash if it changed (another network, channel or router)
void wifiHintSave() {
  String ssid = WiFi.SSID();
  int32_t ch = WiFi.channel();
  if (!ssid.length() || ch < 1 || ch > 13) return;
  WifiHint h = {WIFI_MAGIC, ssidHash(ssid), {}, (uint8_t)ch, 0}, old;
  memcpy(h.bssid, WiFi.BSSID(), 6);
  EEPROM.get(WIFIH_OFF, old);
  if (!memcmp(&old, &h, sizeof h)) return;
  EEPROM.put(WIFIH_OFF, h);
  EEPROM.commit();
}

void htmlEscapeAppend(String &o, const String &s) {
  for (char c : s) {
    if (c == '<') o += "&lt;";
    else if (c == '>') o += "&gt;";
    else if (c == '&') o += "&amp;";
    else if (c == '"') o += "&quot;";
    else o += c;
  }
}

