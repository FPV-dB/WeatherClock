// Erases files, settings (with passwords and the name) and the saved Wi-Fi, then restarts as out of the box.
// The firmware stays. Used by recovery mode and by the panel's "Prepare as a gift".
void factoryWipe() {
  delay(300);
  if (fsOk) LittleFS.format();
  for (int i = 0; i < EE_SIZE; i++) EEPROM.write(i, 0);
  if (fsLayout2()) {  // storage already formatted: without the mark the next boot would format again and offer a backup that doesn't exist
    fsMark = {FS_MAGIC, 0};
    EEPROM.put(FS_OFF, fsMark);
  }
  EEPROM.commit();
  WiFi.persistent(true);
  WiFi.disconnect(true);
  ESP.eraseConfig();
  delay(300);
  ESP.restart();
}

void rotSet(const String &v) {
  String s;
  s.reserve(min((size_t)300, v.length()) + 1);
  for (char c : v)  // only the list format: no quotes or backslashes in the state JSON
    if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == ':' || c == ',' || c == '-' || c == '_') s += c;
  if (s.length() > 300) s = s.substring(0, s.lastIndexOf(',', 300));
  rotList = s;
  rotNext = millis() + cfg.rotMin * 60000UL;
  if (!fsOk) return;
  if (!s.length()) LittleFS.remove("/rotation.txt");
  else {
    File f = LittleFS.open("/rotation.txt", "w");
    if (f) {
      f.print(s);
      f.close();
    }
  }
}

void rotLoop() {
  if (!cfg.rotMin || !rotList.length() || phase != IDLE || previewActive() || inAlbum) return;
  if ((int32_t)(millis() - rotNext) < 0) return;
  if (cfg.mode == 2 && !album.empty() && !rotStepNow) return;  // when alternating with the album, it's scheduleView that advances
  rotNext = millis() + cfg.rotMin * 60000UL;
  fadeOutNow();  // does nothing if scheduleView already cleared it
  // the item after the current face (or the first, if the current one isn't in the list)
  String cur = cfg.theme == THEME_PACK ? String("p:") + cfg.facePkg : String("t:") + cfg.theme, l = rotList + ",";
  int at = ("," + l).indexOf("," + cur + ","), start = at >= 0 ? at + cur.length() + 1 : 0;
  for (int tries = 0; tries < 32; tries++) {  // skips invalid items (pack removed)
    if (start >= (int)l.length()) start = 0;
    int e = l.indexOf(',', start);
    String it = l.substring(start, e);
    start = e + 1;
    if (it.startsWith("t:")) {
      int t = it.substring(2).toInt();
      if (t < 0 || t >= THEME_COUNT) continue;
      cfg.theme = t;  // weatherbox: the rotation's pack stays loaded (reloading it on every pass fragments memory)
    } else if (it.startsWith("p:") && (it.substring(2) == facePackId() || loadPack(it.substring(2)))) {
      cfg.theme = THEME_PACK;
      strlcpy(cfg.facePkg, it.substring(2).c_str(), sizeof cfg.facePkg);
    } else continue;
    uiInvalidate();  // weatherbox: change by fading instead of scrolling
    return;
  }
}

// ---------- end-of-phase notices (Alexa and the like) ----------
// One address per event in /hooks.txt (end of focus, end of break). When the phase ends the clock
// calls the address (GET), and the service fires a routine: Virtual Smart Home and Voice Monkey make
// Alexa speak, IFTTT connects to hundreds of services. It goes unencrypted (http): all three accept it, and
// TLS doesn't fit on the clock. An "https://" pasted in the panel becomes "http://"; the rest of the address is checked
// by safeHttpUrl (security.h) before building the request.

void hooksLoad() {
  File f = fsOk ? LittleFS.open("/hooks.txt", "r") : File();
  if (!f) return;
  hookWork = f.readStringUntil('\n');
  hookBreak = f.readStringUntil('\n');
  f.close();
  hookWork = hookClean(hookWork);
  hookBreak = hookClean(hookBreak);
}

String hookClean(String u) {
  u.trim();
  if (u.startsWith("https://")) u = "http://" + u.substring(8);
  if (!safeHttpUrl(u.c_str(), u.length())) return "";
  return u;
}

// calls the address; returns the HTTP code (0 = no address or no Wi-Fi, negative = connection failure)
int hookFire(const String &url) {
  if (!url.length() || WiFi.status() != WL_CONNECTED) return 0;
  WiFiClient client;
  int code = httpGet(client, url, 4000);
  client.stop();
  return code;
}

