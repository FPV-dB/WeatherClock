// ---------- web ----------
void jsonEscapeAppend(String &o, const char *s) {
  for (; *s; s++) {
    char c = *s;
    if (c == '"' || c == '\\') o += '\\';
    if ((uint8_t)c >= 0x20) o += c;
  }
}

bool safeText(const String &s) { return s.indexOf('"') < 0 && s.indexOf('\\') < 0; }

// The clock's time zone offset right now, in seconds (local time - UTC), from the difference between localtime and gmtime.
int32_t localOffset() {
  time_t now = time(nullptr);
  struct tm lt, gt;
  localtime_r(&now, &lt);
  gmtime_r(&now, &gt);
  int32_t d = (lt.tm_hour - gt.tm_hour) * 3600 + (lt.tm_min - gt.tm_min) * 60;
  int dd = lt.tm_yday - gt.tm_yday;  // day (or year) rollover between the two
  if (dd == 1 || dd < -1) d += 86400;
  else if (dd == -1 || dd > 1) d -= 86400;
  return d;
}

