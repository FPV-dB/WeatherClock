// ---------- firmware update (/update) ----------
// Accepts our firmware and the original GeekMagic one (to go back to factory), but checks the file
// before swapping: an ESP8266 image (0xE9 at the start and in the app), the size and the CRC32 that elf2bin
// writes in the header (offsets 4112 and 4116; every original V9.0.x version has them too) and whether it fits in the
// free space. A truncated, corrupt or other-device file is refused and the current firmware stays.
// User "admin"; an empty password (or recovery mode) skips authentication.
struct OtaCheck { uint32_t got, size, want, crc; uint8_t field[8]; String err; bool authOk, begun, gz, finished; } ota;

void otaConsume(const uint8_t *p, size_t n) {
  for (size_t i = 0; i < n && !ota.err.length(); i++, ota.got++) {
    uint32_t o = ota.got;
    uint8_t v = p[i];
    if ((o == 0 || o == 4096) && v != 0xE9) ota.err = F("not an ESP8266 firmware");
    if (o >= 4112 && o < 4120) {
      ota.field[o - 4112] = v;
      v = 0;  // the size and CRC fields go into the sum as zeros
      if (o == 4119) {
        memcpy(&ota.size, ota.field, 4);
        memcpy(&ota.want, ota.field + 4, 4);
        uint32_t room = (ESP.getFreeSketchSpace() - 0x1000) & 0xFFFFF000;
        if (ota.size < 4120 || (!ota.gz && ota.size > room)) ota.err = F("invalid size or not enough space");  // .gz: checked in otaVerifyGz
      }
    }
    if (ota.size && o >= ota.size) ota.err = F("file larger than stated");
    ota.crc ^= (uint32_t)v << 24;
    for (int k = 0; k < 8; k++) ota.crc = (ota.crc << 1) ^ (ota.crc & 0x80000000 ? 0x04C11DB7 : 0);
  }
}

// ---------- compressed update (.bin.gz) ----------
// The .gz is ~74% of the firmware, so more firmware fits in the 1 MB area: the new version no longer needs
// to fit whole beside the current one. The .gz is written at the END of the area and the boot loader (eboot)
// decompresses it on restart, over the current firmware, sector by sector. A corrupt .gz would leave the
// clock with no firmware; so, before allowing the swap, the clock reads back the written .gz, decompresses
// all of it and checks: the .gz CRC, header, size and CRC of the image (otaConsume) and that the decompressed
// image doesn't reach the .gz the eboot still has to read. If anything fails, the swap is cancelled.
// 8 KB window (build.sh compresses this way): a .gz with a bigger window is refused by uzlib.
static uint32_t gzAddr, gzEnd;
static uint8_t *gzBuf;
static int gzRead(struct uzlib_uncomp *m) {
  if (gzAddr >= gzEnd) return -1;
  uint32_t n = gzEnd - gzAddr < 512 ? gzEnd - gzAddr : 512;
  if (!ESP.flashRead(gzAddr, gzBuf, n)) return -1;
  gzAddr += n;
  m->source = gzBuf + 1;
  m->source_limit = gzBuf + n;
  return gzBuf[0];
}

// weatherbox: the 8 KB dictionary for the .gz check is reserved at the start of the upload (see otaSigBegin)
static uint8_t *otaDict = nullptr;
bool otaVerifyGz() {
  eboot_command cmd;
  if (eboot_command_read(&cmd) || cmd.action != ACTION_COPY_RAW) {
    ota.err = F("update not scheduled");
    return false;
  }
  uint32_t src = cmd.args[0];
  uint8_t *dict = otaDict ? otaDict : (uint8_t *)malloc(8192), out[256];
  otaDict = nullptr;  // now it belongs to the checker: freed at the end, together with the rest
  TINF_DATA *d = (TINF_DATA *)calloc(1, sizeof(TINF_DATA));  // ~1.2 KB of tables: off the stack
  gzBuf = (uint8_t *)malloc(512);
  if (dict && gzBuf && d) {
    gzAddr = src;
    gzEnd = src + cmd.args[2];
    uzlib_init();
    d->source_read_cb = gzRead;
    uzlib_uncompress_init(d, dict, 8192);
    int res = uzlib_gzip_parse_header(d);
    ota.got = ota.size = ota.want = 0;  // otaConsume confere agora a imagem descompactada
    ota.crc = 0xFFFFFFFF;
    while (res == TINF_OK && !ota.err.length()) {
      d->dest_start = d->dest = out;
      d->dest_limit = out + sizeof out;
      res = uzlib_uncompress_chksum(d);
      if (res == TINF_OK || res == TINF_DONE) otaConsume(out, d->dest - out);
      yield();
    }
    if (ota.err.length()) {}
    else if (res != TINF_DONE) ota.err = F("compressed file is corrupt");
    else if (ota.got < 4120 || ota.got != ota.size) ota.err = F("incomplete image");
    else if (ota.crc != ota.want) ota.err = F("image is corrupt (CRC)");
    else if (ota.size > src) ota.err = F("firmware too large to decompress");
    else {
      // The eboot doesn't read the gzip's size: it uses the LAST 4 bytes of the written area as the image
      // size. Anything after the gzip (like 1.20.0's 260 signature bytes) becomes the
      // size, and the eboot writes only the start over sector 0 and erases its own boot
      // loader: the clock no longer boots. The swap is only allowed if that number is the checked image's.
      uint8_t t[4];
      if (cmd.args[2] < 4 || !ESP.flashRead(src + cmd.args[2] - 4, t, 4)) ota.err = F("cannot read the end of the file");
      else if ((uint32_t)(t[0] | t[1] << 8 | t[2] << 16 | (uint32_t)t[3] << 24) != ota.got)
        ota.err = F("data after the gzip (send the .bin.gz without a signature, or the .bin)");
    }
  } else ota.err = F("not enough memory to check the file");
  free(dict);
  free(gzBuf);
  free(d);
  if (ota.err.length()) eboot_command_clear();  // cancela a troca: o firmware atual continua
  return !ota.err.length();
}

// ---------- update signatures ----------
// Over the network, the clock only swaps firmware if the file comes with the project's signature: RSA-2048 over the
// SHA-256 of the file exactly as uploaded (.bin or .bin.gz), in base64 in the X-Firmware-Sig header.
// The signature does NOT go inside the file: in 1.20.0 it went at the end of the .bin.gz and the eboot used the last 4
// bytes as the image size, erasing the boot loader. Nor does it use the core Updater's signature
// (which expects the same suffix). The check is done before Update.end(true): without a valid signature
// nothing is scheduled and the current firmware carries on. Recovery mode (physical: its own network with the password on
// the screen) accepts unsigned firmware, to go back to the original or if the key is lost.
// Only BearSSL's RSA maths (i15, the smallest), with the key as bytes: the core's classes (PublicKey,
// SigningVerifier) pull in the PEM reader and the elliptic curves, ~30 KB more in the firmware.
// The maths runs on the core's extra stack (6.2 KB, allocated only during the check).
extern "C" uint32_t thunk_br_rsa_i15_pkcs1_vrfy(const unsigned char *x, size_t xlen, const unsigned char *oid,
                                                size_t hlen, const br_rsa_public_key *pk, unsigned char *out);
make_stack_thunk(br_rsa_i15_pkcs1_vrfy);
static br_sha256_context otaHash;
// The signature (256 bytes) only exists during the upload: allocated here and freed at the end (or on abort), instead of
// taking up fixed RAM all the time.
static uint8_t *otaSig = nullptr;
static bool otaSigGiven;
// weatherbox: BearSSL's extra stack (6.2 KB) is reserved at the start of the upload, while memory is still
// in one piece; at the end, after hours of fragmentation plus the upload buffers, it might not fit
static bool otaThunk = false;
static void otaSigFree() {
  free(otaSig);
  otaSig = nullptr;
  otaSigGiven = false;
  if (otaThunk) {
    stack_thunk_del_ref();
    otaThunk = false;
  }
  free(otaDict);  // upload interrupted before the check
  otaDict = nullptr;
}

static void otaSigBegin() {
  br_sha256_init(&otaHash);
  otaSigFree();
  const String &b64 = server.header("X-Firmware-Sig");
  if (b64.length() < 340 || b64.length() > 348) return;  // 256 bytes = 344 characters
  char buf[264];
  base64_decodestate st;
  base64_init_decodestate(&st);
  if (base64_decode_block(b64.c_str(), b64.length(), buf, &st) != 256) return;
  otaSig = (uint8_t *)malloc(256);
  if (!otaSig) return;
  memcpy(otaSig, buf, 256);
  otaSigGiven = true;
  if (ESP.getMaxFreeBlockSize() >= 7500) {  // add_ref aborts if it doesn't fit: only ask with room to spare
    stack_thunk_add_ref();
    otaThunk = true;
  }
}

static bool otaSigOk() {
  if (recoveryMode) return true;
  if (!otaSigGiven) {
    ota.err = F("unsigned firmware (use the file from the website, or recovery mode)");
    return false;
  }
  if (!otaThunk && ESP.getMaxFreeBlockSize() < 7500) {  // the maths uses an extra 6.2 KB stack
    ota.err = F("not enough memory to check the signature");
    return false;
  }
  uint8_t n[sizeof OTA_KEY_N], e[sizeof OTA_KEY_E], want[32], got[32];
  memcpy_P(n, OTA_KEY_N, sizeof n);  // BearSSL reads the key byte by byte: it has to be in RAM
  memcpy_P(e, OTA_KEY_E, sizeof e);
  br_rsa_public_key key = {n, sizeof n, e, sizeof e};
  br_sha256_out(&otaHash, want);
  stack_thunk_add_ref();
  bool ok = thunk_br_rsa_i15_pkcs1_vrfy(otaSig, 256, BR_HASH_OID_SHA256, sizeof got, &key, got) &&
            !memcmp(got, want, sizeof got);
  stack_thunk_del_ref();
  if (otaThunk) {  // weatherbox: give the reserved stack back now: the .gz check that comes next needs the memory
    stack_thunk_del_ref();
    otaThunk = false;
  }
  if (!ok) ota.err = F("invalid signature");
  return ok;
}

