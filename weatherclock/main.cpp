// The time passes through a software restart in RTC memory (outside the eboot's blocks 0-31 and the crash's 32-33).
// It comes back as a fallback time: shown straight away, but only SNTP together with the weather confirms it.
const uint32_t RTC_CLOCK_BLOCK = 40;
void rtcTimeSave() {
  if (!timeTrusted()) return;
  eboot_command cmd;
  if (eboot_command_read(&cmd) == 0) return;  // update waiting for the eboot: don't touch RTC memory now
  RtcClock c = rtcClockMake((uint32_t)time(nullptr), system_get_rtc_time());
  ESP.rtcUserMemoryWrite(RTC_CLOCK_BLOCK, (uint32_t *)&c, sizeof c);
}

void rtcTimeRestore() {
  RtcClock c;
  if (!ESP.rtcUserMemoryRead(RTC_CLOCK_BLOCK, (uint32_t *)&c, sizeof c)) return;
  int64_t t = rtcClockRestore(c, system_get_rtc_time(), system_rtc_clock_cali_proc());
  if (t <= 0) return;
  setenv("TZ", cfg.tz, 1);
  tzset();
  softTime(t, 2);
}

// NTP.br answers faster in Brazil; elsewhere the pool picks a nearby server. rot rotates the
// order: if the first didn't answer, lwIP only tries the next one after ~15 s (see sntpWatch).
void applyTimezone(uint8_t rot = 0) {
  const char *s[3] = {"pool.ntp.org", "time.google.com", "a.st1.ntp.br"};
  const char *z = cfg.tz;  // time zones of Brazil and neighbours: "<-03>3", "<-04>4"...
  if (z[0] == '<' && z[1] == '-' && z[2] == '0' && z[3] >= '2' && z[3] <= '5' && z[4] == '>') {
    s[0] = "a.st1.ntp.br";
    s[1] = "pool.ntp.org";
    s[2] = "time.google.com";
  }
  configTime(z, s[rot % 3], s[(rot + 1) % 3], s[(rot + 2) % 3]);
}

// ---------- brightness (with night hours) ----------
// 20 kHz PWM (outside the audible and flicker range) with 1023 steps; inverted pin (0 = fully lit).
// Gamma 2.2 curve (perceptual) over the cfg's 0-100; 1 % already gives ~1 % duty, so it doesn't go dark.
const uint16_t BL_RANGE = 1023;
const uint32_t BL_HZ = 20000;
const uint16_t BL_MIN = 10;      // minimum duty for any brightness > 0
const uint16_t BL_FADE_MS = 400;  // ramp between two levels (day/night, slider)
int curBri = -1;
uint16_t blFrom = 0, blTo = 0, blNow = 0;
uint32_t blT0 = 0;
bool blBoot = true;  // first write (boot): no ramp

uint16_t briDuty(int b) {
  if (b <= 0) return 0;
  return BL_MIN + (uint16_t)((BL_RANGE - BL_MIN) * powf(b / 100.0f, 2.2f) + 0.5f);
}

int16_t sunRise = -1, sunSet = -1;  // minutes of the day (local time), from the last weather fetch

// Called on every loop pass: moves from the current position to the target in BL_FADE_MS and only touches the PWM when it changes
bool fadeHold = false;  // weatherbox: screen dark in the middle of a change (see fadeOutNow)

void briFade() {
  if (fadeHold) return;
  uint32_t el = millis() - blT0;
  uint16_t lvl = el >= BL_FADE_MS ? blTo : blFrom + (int32_t)(blTo - blFrom) * (int32_t)el / (int32_t)BL_FADE_MS;
  if (lvl == blNow) return;
  blNow = lvl;
  analogWrite(PIN_BL, BL_RANGE - lvl);
}

void updateBrightness(bool force = false) {
  int b = cfg.brightness;
  struct tm t;
  if (cfg.nightOn && localNow(t)) {
    int h = t.tm_hour, m = h * 60 + t.tm_min, s = cfg.nightStart, e = cfg.nightEnd;
    bool night = false;
    if (cfg.nightSun && sunRise >= 0 && sunSet > sunRise) night = m < sunRise || m >= sunSet;  // from sunset to sunrise
    else if (s != e) night = s < e ? (h >= s && h < e) : (h >= s || h < e);  // fixed hours (or no sun data yet)
    if (night) b = cfg.nightBri;
  }
  if (b == curBri && !force) return;
  curBri = b;
  blFrom = blNow;
  blTo = briDuty(b);
  blT0 = millis();
  if (blBoot) {  // boot: lights straight to the requested level
    blBoot = false;
    blFrom = blTo;
    blNow = blTo;
    analogWrite(PIN_BL, BL_RANGE - blTo);
    return;
  }
  briFade();
}

// weatherbox: screen change by fading. There is no memory to blend two screens, so the brightness drops
// to zero, the new screen is drawn in the dark and the brightness comes back (briFade does the ramp up in BL_FADE_MS).
bool fadeInPending = false;
void fadeOutNow() {
  if (fadeHold) return;
  const uint16_t from = blNow;
  const uint32_t t0 = millis(), D = 220;
  for (;;) {
    const uint32_t e = millis() - t0;
    const uint16_t l = e >= D ? 0 : from - (uint32_t)from * e / D;
    analogWrite(PIN_BL, BL_RANGE - l);
    if (e >= D) break;
    delay(8);
  }
  blNow = 0;
  fadeHold = true;
  fadeInPending = true;
}
void fadeInStart() {
  if (!fadeHold) return;
  fadeHold = false;
  fadeInPending = false;
  blFrom = 0;
  blNow = 0;
  blT0 = millis();
  blTo = briDuty(curBri);
}

