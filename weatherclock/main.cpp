// weatherbox: corner reserved for the radar clock (the GIF doesn't draw there, so it doesn't flicker)
int16_t gifMaskX = 240, gifMaskY = 240;
char cornerHM[8] = "";

void gifDraw(GIFDRAW *p) {
  uint16_t *buf = uiRowBuf();  // aligned: tftPixels doesn't copy
  int y = p->iY + p->y + gifOffY;
  if (y < 0 || y >= 240) return;
  int x0 = p->iX + gifOffX;
  int w = p->iWidth;
  if (x0 + w > 240) w = 240 - x0;
  if (y >= gifMaskY && x0 + w > gifMaskX) w = gifMaskX - x0;
  if (w <= 0) return;
  uint8_t *s = p->pPixels;
  uint16_t *pal = p->pPalette;
  if (p->ucDisposalMethod == 2) {  // restore the background
    for (int i = 0; i < w; i++)
      if (s[i] == p->ucTransparent) s[i] = p->ucBackground;
    p->ucHasTransparency = 0;
  }
  tft.startWrite();
  if (p->ucHasTransparency) {
    uint8_t tr = p->ucTransparent;
    int x = 0;
    while (x < w) {
      while (x < w && s[x] == tr) x++;
      int start = x, n = 0;
      while (x < w && s[x] != tr) buf[n++] = pal[s[x++]];
      if (n) {
        tft.setAddrWindow(x0 + start, y, n, 1);
        tftPixels(buf, n);
      }
    }
  } else {
    for (int i = 0; i < w; i++) buf[i] = pal[s[i]];
    tft.setAddrWindow(x0, y, w, 1);
    tftPixels(buf, w);
  }
  tft.endWrite();
}

// weatherbox: a face pack takes about 8 KB of RAM, and the GIF decoder (~24 KB contiguous) or the
// JPEG one (~18 KB) doesn't fit beside it. While the album is showing, the pack leaves RAM and comes back afterwards.
bool loadPack(const String &id);
static String packHeld;
static void packHold() {
  if (packHeld.length() || !facePackId()[0]) return;
  packHeld = facePackId();
  facePackUnload();
}
static void packResume() {
  if (!packHeld.length()) return;
  String id = packHeld;
  packHeld = "";
  loadPack(id);
}

void stopAlbum() {
  if (gif) {
    gif->close();
    delete gif;
    gif = nullptr;
  }
  if (wcrOn) {
    wcrFile.close();
    wcrOn = false;
  }
  inAlbum = false;
  curFile = "";
  gifMaskX = gifMaskY = 240;
  cornerHM[0] = 0;
  packResume();
  uiInvalidate();  // the clock redraws everything when it comes back
}

// weatherbox: memory fragments over the hours (the face pack comes and goes on every change) and the GIF
// can no longer find ~24 KB contiguous. In that case the clock restarts by itself, at most once per hour of use.
uint32_t memRestartAt = 0;

bool showAlbumItem(const String &f) {
  stopAlbum();
  if (!LittleFS.exists(f)) return false;
  if (!isWcr(f)) packHold();  // the .wcr uses almost no memory: the face can stay loaded
  tft.fillScreen(0);
  uiInvalidate();
  inAlbum = true;
  curFile = f;
  if (isWcr(f)) {
    wcrFile = LittleFS.open(f, "r");
    if (!wcrOpen(wcrFile, wcrFrames, wcrDelay, wcrData)) {
      wcrFile.close();
      uiError(tr("Arquivo invalido", "Invalid file", "Archivo invalido"));
      return false;
    }
    wcrOn = true;
    wcrFrame = 0;
    wcrData1 = 0;
    {
      uint8_t hb[10];
      File h = LittleFS.open(f, "r");
      wcrWrap = h && h.read(hb, 10) == 10 && hb[9] == 1 && wcrFrames > 2;
      h.close();
    }
    nextFrameAt = 0;
    return true;
  }
  if (isGif(f)) {
    if (!validGif(f)) {
      uiError(tr("GIF fora do padrao", "Unsupported GIF", "GIF fuera de norma"));
      return false;
    }
    gif = new (std::nothrow) AnimatedGIF();  // ~8 KB here + two 8 KB tables in begin()
    if (gif) gif->begin(GIF_PALETTE_RGB565_LE);
    if (gif && !gif->ready()) {
      delete gif;
      gif = nullptr;
    }
    if (!gif) {
      uiError(tr("Sem memoria p/ GIF", "No memory for GIF", "Sin memoria p/ GIF"));
      if (millis() > 3600000UL && !memRestartAt) memRestartAt = millis() | 1;
      return true;  // keeps the warning screen until the next item
    }
    if (!gif->open(f.c_str(), mediaOpen, mediaClose, gifRead, gifSeek, gifDraw)) {
      gif->close();
      delete gif;
      gif = nullptr;
      uiError(tr("GIF invalido", "Invalid GIF", "GIF invalido"));
      return false;
    }
    gifOffX = max(0, (240 - gif->getCanvasWidth()) / 2);
    gifOffY = max(0, (240 - gif->getCanvasHeight()) / 2);
    nextFrameAt = 0;
  } else {
    if (!drawJpg(f)) uiError(tr("JPG invalido", "Invalid JPG", "JPG invalido"));
  }
  return true;
}

void albumLoop() {
  if ((!gif && !wcrOn) || (int32_t)(millis() - nextFrameAt) < 0) return;
  if (wcrOn) {
    if (!wcrDrawFrame()) {
      stopAlbum();
      return;
    }
    nextFrameAt = millis() + max((int)wcrDelay[wcrFrame], 20);
    if (wcrFrame == 0 && !wcrData1) wcrData1 = wcrFile.position();
    if (++wcrFrame >= wcrFrames) {  // end: with the wrap frame, carry on from the second; otherwise from the first
      if (wcrWrap && wcrData1) {
        wcrFrame = 1;
        wcrFile.seek(wcrData1);
      } else {
        wcrFrame = 0;
        wcrFile.seek(wcrData);
      }
    }
  } else {
    int delayMs = 0;
    int r = gif->playFrame(false, &delayMs);
    if (r < 0) {  // error: give up on this GIF
      stopAlbum();
      return;
    }
    if (r == 0) gif->reset();  // last frame: start over
    nextFrameAt = millis() + max(delayMs, 20);
  }
  // weatherbox: on the radar, the current time in the corner; the GIF doesn't draw there, so it only redraws when it changes
  struct tm t;
  if (curFile.indexOf("radar") >= 0 && localNow(t)) {
    char hm[8];
    int h = t.tm_hour;
    if (cfg.hour12) h = h % 12 == 0 ? 12 : h % 12;
    snprintf(hm, sizeof hm, "%02d:%02d", h, t.tm_min);
    if (strcmp(hm, cornerHM)) {
      strlcpy(cornerHM, hm, sizeof cornerHM);
      uiCornerClock(hm);
      gifMaskX = 240 - (int)strlen(hm) * 12 - 11;  // same box as uiCornerClock
      gifMaskY = 212;
    }
  }
}

// Decides what to show when there's no Pomodoro: the clock or an album item.
void scheduleView() {
  uint32_t now = millis();
  if (viewUntil && (int32_t)(now - viewUntil) < 0) return;
  bool wantAlbum = !album.empty() && (cfg.mode == 1 || (cfg.mode == 2 && !inAlbum));
  if (wantAlbum) {
    const String &next = album[albumIdx++ % album.size()];
    // with a single item, don't redraw the same photo (avoids flicker and restarting the GIF)
    if (!(inAlbum && next == curFile)) {
      fadeOutNow();
      showAlbumItem(next);
    }
  } else if (inAlbum) {
    fadeOutNow();
    stopAlbum();
    // weatherbox: when alternating with the album, the rotation advances here, on the way back to the clock, and not by its own
    // timer: each face and each album item stays on screen for exactly "Seconds per item"
    rotNext = millis();
    rotStepNow = true;
    rotLoop();
    rotStepNow = false;
  }
  viewUntil = now + cfg.albumDelay * 1000UL;
  if (!viewUntil) viewUntil = 1;
}

// ---------- face packs (/faces/<id>.json) ----------
bool idOk(const String &id) {
  if (!id.length() || id.length() > 23) return false;
  for (char c : id)
    if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' || c == '_')) return false;
  return true;
}

// Reads the file and loads it into the engine. On error, msg gets the reason.
bool loadPackFile(const String &path, String &msg) {
  File f = fsOk ? LittleFS.open(path, "r") : File();
  if (!f) {
    msg = F("file not found");
    return false;
  }
  size_t n = f.size();
  if (n == 0 || n > 16384) {
    f.close();
    msg = F("face pack empty or larger than 16 KB");
    return false;
  }
  char err[96];
  bool ok = facePackLoadFile(f, err, sizeof err);  // in passes: the JSON doesn't fit in RAM whole
  f.close();
  if (!ok) msg = err;
  uiInvalidate();
  return ok;
}

bool loadPack(const String &id) {
  String msg;
  return idOk(id) && loadPackFile("/faces/" + id + ".json", msg);
}

