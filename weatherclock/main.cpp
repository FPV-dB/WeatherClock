// ---------- storage: everything that takes up file storage ----------
// The album only shows photos and GIFs, but storage holds more: downloaded faces, the panel, the history
// and, on clocks that came from the original firmware, its files. /api/storage lists everything, in parts
// (without building the whole list in RAM); /api/fsdelete deletes a file or a whole folder, except what
// the clock needs to work (fsKeep).
bool fsKeep(const String &p) {
  if (p == "/stats.bin" || p == "/hooks.txt" || p == "/rotation.txt" || p == "/www" || p.startsWith("/www/")) return true;
  if (p == "/image" || p == "/gif" || p == "/faces") return true;  // the folders stay; what's inside can go
  return cfg.theme == THEME_PACK && p.startsWith(String("/faces/") + cfg.facePkg + ".");  // face in use
}

void sendStorage() {
  if (!readOk()) return;
  static FSInfo fi;
  if (fsOk) LittleFS.info(fi);
  server.sendHeader("Cache-Control", "no-store");
  server.setContentLength(CONTENT_LENGTH_UNKNOWN);
  server.send(200, "application/json", "");
  server.sendContent("{\"used\":" + String(fsOk ? fi.usedBytes : 0) + ",\"total\":" + String(fsOk ? fi.totalBytes : 0) +
                     ",\"block\":" + String(fsOk ? fi.blockSize : 0) + ",\"files\":[");
  std::vector<String> dirs = {"/"};
  bool first = true;
  int n = 0;
  for (size_t k = 0; fsOk && k < dirs.size() && n < 1000; k++) {  // folder by folder (breadth first)
    Dir d = LittleFS.openDir(dirs[k]);
    String base = dirs[k] == "/" ? "" : dirs[k];
    String chunk;
    while (d.next() && n < 1000) {
      String p = base + "/" + d.fileName();
      bool dir = d.isDirectory();
      if (dir && dirs.size() < 64) dirs.push_back(p);
      chunk += first ? F("{\"p\":\"") : F(",{\"p\":\"");
      first = false;
      jsonEscapeAppend(chunk, p.c_str());
      chunk += F("\",\"s\":");
      chunk += dir ? 0 : d.fileSize();
      if (dir) chunk += F(",\"d\":1");
      if (fsKeep(p)) chunk += F(",\"k\":1");
      chunk += '}';
      n++;
      if (chunk.length() > 700) {
        server.sendContent(chunk);
        chunk = "";
      }
      yield();
    }
    if (chunk.length()) server.sendContent(chunk);
  }
  server.sendContent("]}");
  server.sendContent("");  // end of the chunked reply
}

// deletes folder p and everything inside (at most 8 levels); the names are read before deleting
bool fsRemoveAll(const String &p, int depth) {
  if (depth > 8) return false;
  std::vector<String> files, dirs;
  Dir d = LittleFS.openDir(p);
  while (d.next()) (d.isDirectory() ? dirs : files).push_back(p + "/" + d.fileName());
  bool ok = true;
  for (const String &f : files) ok = LittleFS.remove(f) && ok;
  for (const String &s : dirs) ok = fsRemoveAll(s, depth + 1) && ok;
  if (LittleFS.exists(p)) ok = LittleFS.rmdir(p) && ok;  // the core's LittleFS may already have removed the empty folder
  return ok;
}

// ---------- panel protection ----------
// Any site open in the browser can send requests to the clock's IP (CSRF: wipe the Wi-Fi,
// format, write a firmware) or, by pointing a name of its own at that IP, even read the replies (DNS
// rebinding). So:
//  - every action requires the X-SmallTV header, which only the panel sends: an outside site can't (the
//    browser would ask for a CORS permission the clock never gives);
//  - the request must arrive via the clock's IP (Host header with digits only), not via a name.
// Left out are the Alexa API (the Echo doesn't send the header; it only starts and stops the Pomodoro), the
// Wi-Fi portal and recovery mode (they require being near the clock).
bool hostOk() {
  const String &h = server.hostHeader();
  // A real IPv4 (4 parts up to 255, optional port) or this clock's exact .local name
  return safeIpv4Host(h.c_str(), h.length()) || safeOwnHost(h.c_str(), h.length(), netName) ||
         (lanName[0] && safeOwnHost(h.c_str(), h.length(), lanName));
}
bool panelOk() { return hostOk() && server.header("X-SmallTV") == "1"; }
bool deny() {
  server.send_P(403, PSTR("text/plain"), PSTR("Forbidden"));
  return false;
}
// Panel password (the same as /update, user admin): once set, the whole panel and API ask for
// HTTP login (the browser asks once and remembers). Failures get a progressive delay per IP without blocking
// the clock's loop. The Alexa API and recovery mode don't ask for a password.
// Basic login is checked here: the server's authenticate() pulls in Digest mode and MD5 too (~2.5 KB).
bool passOk() {
  return !cfg.otaPass[0] || server.header("Authorization") == "Basic " + base64::encode(String("admin:") + cfg.otaPass, false);
}
void askLogin() {
  server.sendHeader(F("WWW-Authenticate"), F("Basic realm=\"Weather Clock\""));
  server.send(401, "text/plain", "");
}
