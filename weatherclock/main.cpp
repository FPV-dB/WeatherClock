// Reads and checks the header; leaves the file at the first frame
bool wcrOpen(File &f, uint8_t &frames, uint16_t *delays, uint32_t &data) {
  uint8_t h[10];
  if (!f || f.read(h, 10) != 10 || memcmp(h, "WCR2", 4)) return false;
  const uint16_t w = h[4] | h[5] << 8, ht = h[6] | h[7] << 8;
  frames = h[8];
  if (w != 240 || ht != 240 || !frames || frames > 32) return false;
  for (int i = 0; i < frames; i++) {
    uint8_t d[2];
    if (f.read(d, 2) != 2) return false;
    delays[i] = d[0] | d[1] << 8;
  }
  data = 10 + 2 * frames;
  return true;
}

bool validWcr(const String &path) {
  File f = LittleFS.open(path, "r");
  uint8_t n;
  uint16_t d[32];
  uint32_t data;
  const bool ok = wcrOpen(f, n, d, data) && f.size() > data + 4;
  f.close();
  return ok;
}

extern int16_t gifMaskX, gifMaskY;
// One frame: records n < 0x80 = n pixels of the following colour (RGB565); n >= 0x80 = (n & 0x7F) + 1 pixels that
// stay as they are (the previous frame). Builds row spans and sends each span finished (no flicker).
bool wcrDrawFrame() {
  uint8_t lb[4];
  if (wcrFile.read(lb, 4) != 4) return false;
  uint32_t left = lb[0] | lb[1] << 8 | (uint32_t)lb[2] << 16 | (uint32_t)lb[3] << 24;
  uint8_t in[192];
  int have = 0, pos = 0;
  auto next = [&](int &b) -> bool {
    if (pos == have) {
      if (!left) return false;
      have = wcrFile.read(in, left < sizeof in ? left : sizeof in);
      if (have <= 0) return false;
      left -= have;
      pos = 0;
    }
    b = in[pos++];
    return true;
  };
  uint16_t *row = uiRowBuf();
  int x = 0, y = 0, span = -1;  // span: start of the painted span not yet sent
  auto flush = [&]() {
    if (span < 0) return;
    int end = x;
    if (y >= gifMaskY && end > gifMaskX) end = gifMaskX;  // the radar's clock corner is left out
    if (end > span) {
      tft.setAddrWindow(span, y, end - span, 1);
      tftPixels(row + span, end - span);
    }
    span = -1;
  };
  tft.startWrite();
  int n, lo, hi;
  while (y < 240 && next(n)) {
    if (n & 0x80) {  // skip: keep what's already on screen
      int k = (n & 0x7F) + 1;
      while (k > 0 && y < 240) {
        flush();
        const int step = k < 240 - x ? k : 240 - x;
        x += step;
        k -= step;
        if (x == 240) { x = 0; y++; }
      }
      continue;
    }
    if (!next(lo) || !next(hi)) break;
    const uint16_t c = lo | hi << 8;
    while (n > 0 && y < 240) {
      if (span < 0) span = x;
      const int step = n < 240 - x ? n : 240 - x;
      for (int j = 0; j < step; j++) row[x + j] = c;
      x += step;
      n -= step;
      if (x == 240) {
        flush();
        x = 0;
        y++;
      }
    }
    if ((y & 15) == 0) yield();
  }
  flush();
  tft.endWrite();
  if (left) wcrFile.seek(wcrFile.position() + left);
  return y == 240;
}
