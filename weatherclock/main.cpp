// Pixel rows for the screen. Adafruit GFX 1.13 sends each row through SPI.writeBytes, which reads
// memory 4 bytes at a time: with the row at an address that isn't a multiple of 4 (vector font text,
// clips, odd-width strips) the ESP8266 raises an alignment exception and restarts (issue #4).
// Every row passes through here: if misaligned, it goes through an aligned copy.
// The aligned copy uses uiRowBuf(), the same buffer as gifDraw and Flip (never in use at the same time): anything
// already aligned isn't copied. One buffer instead of three (fixed RAM).
static void tftPixels(uint16_t *px, int n) {
  if (!((uintptr_t)px & 3)) {
    tft.writePixels(px, n);
    return;
  }
  while (n > 0) {
    int k = n < 240 ? n : 240;
    memmove(uiRowBuf(), px, k * 2);  // px may be inside the buffer itself (a clipped Flip row)
    tft.writePixels(uiRowBuf(), k);
    px += k;
    n -= k;
  }
}

// drawRGBBitmap with the screen clipping done first, so each row goes through tftPixels
static void tftBitmap(int16_t x, int16_t y, uint16_t *px, int16_t w, int16_t h) {
  int x0 = max<int>(x, 0), y0 = max<int>(y, 0), x1 = min<int>(x + w, tft.width()), y1 = min<int>(y + h, tft.height());
  if (x1 <= x0 || y1 <= y0) return;
  tft.startWrite();
  tft.setAddrWindow(x0, y0, x1 - x0, y1 - y0);
  for (int r = y0; r < y1; r++) tftPixels(px + (r - y) * w + (x0 - x), x1 - x0);
  tft.endWrite();
}

