// Colour order, inversion and rotation vary between units of the SmallTV: all configurable in the panel.
// Vertical hardware scrolling (VSCRDEF 0x33 / VSCSAD 0x37), used by uiScroll* in ui.cpp.
// The ST7789's RAM has 320 rows and the 240 glass shows the first 240 the panel READS (displayed row n
// shows RAM row n + VSCSAD). Where the rows the library writes end up in RAM:
//   normal (setRotation(2), MADCTL without MY): row address = y, y = 0..239 -> RAM 0..239; the margin
//     (80 rows with no glass) is address 240..319.
//   rotated (setRotation(0), MADCTL MX|MY): address = y + 80, and MY mirrors the RAM (RAM = 319 - address),
//     so y = 0..239 -> RAM 239..0 and the margin is address 0..79 (RAM 319..240).
// MY only mirrors write access; VSCSAD is still in displayed rows. So, for the content to move up
// from the viewer's point of view, rotated needs VSCSAD = rows - offset (uiScrollSad in ui.h). The chip scrolls the
// whole area at once: here TFA = BFA = 0 and VSA = rows (the fixed bands don't fit, see ui.h).
// In either case, drawing's y = 0..239 stays the same address during the scroll.
static int16_t scrollDef = 0;  // VSA sent last (0 = not yet)
static void tftScroll(int16_t rows, int16_t offset) {
  int16_t r = rows ? rows : 320;
  if (r != scrollDef) {
    uint8_t d[6] = {0, 0, (uint8_t)(r >> 8), (uint8_t)r, (uint8_t)((320 - r) >> 8), (uint8_t)(320 - r)};
    tft.sendCommand(0x33, d, 6);
    scrollDef = r;
  }
  uint16_t sad = uiScrollSad(cfg.flip, r, offset);
  uint8_t a[2] = {(uint8_t)(sad >> 8), (uint8_t)sad};
  tft.sendCommand(0x37, a, 2);
}
// Blacks out the RAM margin (80 rows beyond the glass). It's never drawn after this: it only shows
// during a scroll, and the RAM's old contents (garbage after power-on) would show in the gap.
static void tftClearMargin() {
  uint16_t a0 = cfg.flip ? 0 : 240;  // row addresses of the margin, without the library's offset
  uint8_t ca[4] = {0, 0, 0, 239}, ra[4] = {(uint8_t)(a0 >> 8), (uint8_t)a0, (uint8_t)((a0 + 79) >> 8), (uint8_t)(a0 + 79)};
  tft.sendCommand(ST77XX_CASET, ca, 4);
  tft.sendCommand(ST77XX_RASET, ra, 4);
  tft.startWrite();
  tft.writeCommand(ST77XX_RAMWR);
  tft.writeColor(0, 240UL * 80);
  tft.endWrite();
}
void applyPanel() {
  uiScrollEnd();
  tft.setRotation(cfg.flip ? 0 : 2);  // Adafruit: 2 = no mirroring/offsets 0; 0 = 180° (offset 80 already handled)
  uint8_t madctl = (cfg.flip ? (ST77XX_MADCTL_MX | ST77XX_MADCTL_MY) : 0) | (cfg.bgr ? 0x08 : 0);
  tft.sendCommand(ST77XX_MADCTL, &madctl, 1);
  tft.invertDisplay(cfg.invert);
  tft.fillScreen(0);
  tftClearMargin();
  uiInvalidate();
}

