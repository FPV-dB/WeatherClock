void command(const String &c) {
  if (c == "start") {
    if (phase == IDLE) startPhase(WORK, true);
    else { running = true; lastTick = millis(); }
  } else if (c == "pause") {
    running = false;
  } else if (c == "toggle") {
    command(running ? "pause" : "start");
  } else if (c == "skip") {
    if (phase != IDLE) advance(false);
  } else if (c == "reset") {
    phase = IDLE;
    running = false;
    cycleDone = 0;
  } else if (c == "focus") {
    startPhase(WORK, true);
  } else if (c == "short") {
    startPhase(SHORT_BREAK, true);
  } else if (c == "long") {
    startPhase(LONG_BREAK, true);
  } else if (c == "colortest") {
    colorTestRequested = true;
  }
}

// ---------- Alexa ----------
// The clock shows up to Alexa as dimmable lights on a Philips Hue bridge, on the local network: no
// account, skill or cloud. It's the same protocol as Espalexa (the same replies, which Echo devices accept),
// cut down to what the Pomodoro uses and without colour: the whole library would cost ~26 KB of flash.
//   discovery: the Echo sends an M-SEARCH over SSDP (UDP 239.255.255.250:1900) and reads /description.xml;
//   control:   GET /api/<user>/lights and PUT /api/<user>/lights/<id>/state {"on":..,"bri":..}.
// Lights (the name comes out in the clock's language at discovery time):
//   Pomodoro    on: starts focus (or resumes a paused one); off: pauses, and again ends it;
//               "to 50%": a 50-minute focus
//   Break       on: short break ("to 10%": 10 minutes); off: back to focus
//   Long break  on: long break ("to 30%": 30 minutes); off: back to focus
// The lit light shows the current phase in the Alexa app.
// Network name, so nobody has to remember the IP:
//  - lanName: http://weatherclock.local; with another clock already using it, weatherclock-2.local, -3... (checked on connect)
//  - netName: "weatherclock-" + 4 hex digits of the chip, always valid as a fallback and used for DHCP.
// Only the A record, with the packet reader in security.h (tested): ESP8266mDNS would cost ~21 KB.
char netName[24], lanName[20];  // weatherbox: "weatherclock-xxxx" is longer than "smalltv-xxxx"
WiFiUDP hueUdp;
WiFiUDP mdnsUdp;
IPAddress mdnsIp;

void mdnsSend(const char *name, uint16_t id, bool legacy, bool direct) {
  uint8_t out[80], ip[4] = {mdnsIp[0], mdnsIp[1], mdnsIp[2], mdnsIp[3]};
  size_t m = mdnsAnswer(out, sizeof out, name, ip, id, legacy);
  if (!m) return;
  if (direct) mdnsUdp.beginPacket(mdnsUdp.remoteIP(), mdnsUdp.remotePort());
  else mdnsUdp.beginPacketMulticast(IPAddress(224, 0, 0, 251), 5353, mdnsIp);
  mdnsUdp.write(out, m);
  mdnsUdp.endPacket();
}

void mdnsAnnounce() {
  if (lanName[0]) mdnsSend(lanName, 0, false, false);
  mdnsSend(netName, 0, false, false);
}

bool mdnsJoin() {
  mdnsIp = WiFi.localIP();
  mdnsUdp.stop();
  return mdnsUdp.beginMulticast(mdnsIp, IPAddress(224, 0, 0, 251), 5353);
}

// Is someone already answering for this name? Asks 3 times, 250 ms each (RFC 6762, 8.1).
bool mdnsTaken(const char *name) {
  uint8_t q[48], b[256];
  size_t m = mdnsProbeQuery(q, sizeof q, name);
  for (int t = 0; t < 3 && m; t++) {
    mdnsUdp.beginPacketMulticast(IPAddress(224, 0, 0, 251), 5353, mdnsIp);
    mdnsUdp.write(q, m);
    mdnsUdp.endPacket();
    for (uint32_t t0 = millis(); millis() - t0 < 250; delay(10)) {
      if (mdnsUdp.parsePacket() <= 0) continue;
      int n = mdnsUdp.read(b, sizeof b);
      if (n > 0 && mdnsHasAnswer(b, n, name)) return true;
    }
  }
  return false;
}

// On connect: picks the free short name and announces itself.
bool mdnsUp = false;  // Wi-Fi connected on the last mdnsLoop pass (reconnected: join the group again)

void mdnsStart() {
  // No Wi-Fi power saving: dozing between beacons, the ESP8266 loses multicast packets and
  // .local disappears "sometimes". The clock lives on mains power; the cost is ~15 mA.
  WiFi.setSleepMode(WIFI_NONE_SLEEP);
  lanName[0] = 0;
  mdnsUp = true;
  if (!mdnsJoin()) return;
  for (int i = 1; i <= 9; i++) {
    char name[sizeof lanName];
    if (i == 1) strlcpy(name, HOSTNAME, sizeof name);
    else snprintf(name, sizeof name, HOSTNAME "-%d", i);
    if (!mdnsTaken(name)) {
      strlcpy(lanName, name, sizeof lanName);
      break;
    }
  }
  mdnsAnnounce();
}

void mdnsLoop() {
  if (WiFi.status() != WL_CONNECTED) {
    mdnsUp = false;
    return;
  }
  if (!mdnsUp || WiFi.localIP() != mdnsIp) {  // reconnected or the IP changed: join the group again and announce
    mdnsUp = true;
    if (mdnsJoin()) mdnsAnnounce();
  }
  int len = mdnsUdp.parsePacket();
  if (len <= 0) return;
  uint8_t b[256];  // the question comes first; the rest (known answers) can be left out
  int n = mdnsUdp.read(b, sizeof b);
  if (n <= 0) return;
  bool legacy = mdnsUdp.remotePort() != 5353, qu = false;
  uint16_t id = (uint16_t)(b[0] << 8 | b[1]);
  const char *name = lanName[0] && mdnsAsksFor(b, n, lanName, &qu) ? lanName : mdnsAsksFor(b, n, netName, &qu) ? netName : nullptr;
  if (!name) return;
  mdnsSend(name, id, legacy, legacy || qu);
  // Ordinary question (multicast answer): also send a direct copy to whoever asked. Some routers
  // don't pass multicast between Wi-Fi devices; Windows, macOS and Android accept the direct answer.
  if (!legacy && !qu) mdnsSend(name, id, false, true);
}
