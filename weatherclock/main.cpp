// ---------- focus history (/stats.bin) ----------
// One counter per day in a ring of 371 days (53 weeks): gives the streak of days with the goal reached,
// the record and the panel's garden. Only the header stays in RAM; the days are read from the file.
struct StatsHead { uint32_t magic; uint16_t lastDay, best; uint32_t total; };
const uint32_t STATS_MAGIC = 0x544F4D31;  // "TOM1"
const uint16_t STATS_DAYS = 371;
StatsHead stats = {0, 0, 0, 0};
uint16_t statsStreak = 0, statsBest = 0;
bool statsWritePending = false;
uint16_t statsPendingDay = 0;
uint8_t statsPendingCount = 0;
bool fsWriterBusy();
void statsFlush(void);

// days since 1970-01-01 for the local date ("days from civil" algorithm)
uint16_t dayNumber(const struct tm &t) {
  int y = t.tm_year + 1900, m = t.tm_mon + 1;
  y -= m <= 2;
  int era = y / 400, yoe = y - era * 400, doy = (153 * (m + (m > 2 ? -3 : 9)) + 2) / 5 + t.tm_mday - 1;
  return era * 146097 + yoe * 365 + yoe / 4 - yoe / 100 + doy - 719468;
}

// reads the 371 days in order (oldest first); false with no file
bool statsRead(uint8_t *days) {
  File f = fsOk ? LittleFS.open("/stats.bin", "r") : File();
  if (!f || f.size() != sizeof(StatsHead) + STATS_DAYS) return false;
  uint8_t ring[STATS_DAYS];
  f.seek(sizeof(StatsHead));
  f.read(ring, STATS_DAYS);
  f.close();
  for (int i = 0; i < STATS_DAYS; i++) days[i] = ring[(stats.lastDay + 1 + i) % STATS_DAYS];
  return true;
}

void statsCompute() {
  uint8_t d[STATS_DAYS];
  statsStreak = 0;
  if (stats.magic == STATS_MAGIC && statsRead(d)) {
    int i = STATS_DAYS - 1;
    if (d[i] < cfg.dailyGoal) i--;  // today hasn't reached it yet: the streak runs up to yesterday
    for (; i >= 0 && d[i] >= cfg.dailyGoal; i--) statsStreak++;
  }
  if (statsStreak > stats.best) stats.best = statsStreak;
  statsBest = stats.best;
}

// writes day "day" with "count" sessions, zeroing the days skipped since the last record
void statsWrite(uint16_t day, uint8_t count) {
  if (!fsOk) return;
  // LittleFS 2.5.1 can corrupt data with two files open for writing. An upload stays
  // open between handleClient() calls, so only the latest history update is kept
  // and written after the upload ends.
  if (fsWriterBusy()) {
    statsPendingDay = day;
    statsPendingCount = count;
    statsWritePending = true;
    return;
  }
  File f = LittleFS.open("/stats.bin", "r+");
  bool fresh = !f || f.size() != sizeof(StatsHead) + STATS_DAYS;  // no file (or formatted storage)
  if (fresh) {
    if (f) f.close();
    f = LittleFS.open("/stats.bin", "w+");
  }
  if (!f) return;
  if (!fresh && stats.magic == STATS_MAGIC && day < stats.lastDay) {  // the time went backwards: erase nothing
    f.close();
    return;
  }
  if (fresh || stats.magic != STATS_MAGIC || day - stats.lastDay >= STATS_DAYS) {
    if (stats.magic != STATS_MAGIC) stats = {STATS_MAGIC, day, 0, 0};
    // header and the 371 days in sequence from the start: LittleFS doesn't allow seeking past the end
    // of the file (the seek fails). Up to 1.18.2 this code skipped the header in an empty file, the file
    // ended up at 371 bytes and the next boot threw the history away (see statsLoad).
    uint8_t zero[64] = {0};
    f.seek(0);
    f.write((const uint8_t *)&stats, sizeof stats);
    for (int i = 0; i < STATS_DAYS; i += sizeof zero) f.write(zero, min((int)sizeof zero, STATS_DAYS - i));
  } else
    for (uint16_t d = stats.lastDay + 1; d < day; d++) {  // days with the clock switched off: zero
      f.seek(sizeof(StatsHead) + d % STATS_DAYS);
      f.write((uint8_t)0);
    }
  f.seek(sizeof(StatsHead) + day % STATS_DAYS);
  f.write(count);
  stats.lastDay = day;
  f.seek(0);
  f.write((const uint8_t *)&stats, sizeof stats);
  f.close();
}

// history (oldest first) for the garden, the achievements, the share card and the backup
void sendStats() {
  if (!readOk()) return;
  uint8_t d[STATS_DAYS];
  bool ok = stats.magic == STATS_MAGIC && statsRead(d);
  String j;
  j.reserve(STATS_DAYS * 3 + 96);
  j = F("{\"day\":");
  j += stats.lastDay;
  j += F(",\"goal\":");
  j += cfg.dailyGoal;
  j += F(",\"streak\":");
  j += statsStreak;
  j += F(",\"best\":");
  j += statsBest;
  j += F(",\"total\":");
  j += stats.total;
  j += F(",\"days\":[");
  for (int i = 0; i < STATS_DAYS; i++) {
    if (i) j += ',';
    j += ok ? d[i] : 0;
  }
  j += "]}";
  server.send(200, "application/json", j);
}

void statsLoad() {
  File f = fsOk ? LittleFS.open("/stats.bin", "r") : File();
  size_t n = f ? f.size() : 0;
  if (n == sizeof(StatsHead) + STATS_DAYS) f.read((uint8_t *)&stats, sizeof stats);
  else if (n >= STATS_DAYS && n < sizeof(StatsHead) + STATS_DAYS) {
    // short file written up to 1.18.2 (see statsWrite): same header and the days from byte 12,
    // only with the end missing. Recovers what's there and rewrites it at the right size.
    uint8_t ring[STATS_DAYS] = {0};
    f.read((uint8_t *)&stats, sizeof stats);
    f.read(ring, n - sizeof(StatsHead));
    f.close();
    File w = stats.magic == STATS_MAGIC ? LittleFS.open("/stats.bin", "w") : File();
    if (w) {
      w.write((const uint8_t *)&stats, sizeof stats);
      w.write(ring, STATS_DAYS);
      w.close();
    }
  }
  if (f) f.close();
  if (stats.magic != STATS_MAGIC) stats = {0, 0, 0, 0};
  statsCompute();
}

void statsFocus() {
  struct tm t;
  if (!localNow(t) || !timeTrusted()) {  // no confirmed time: keep it and write it once confirmed (statsFlush)
    if (statsPending < 255) statsPending++;
    return;
  }
  stats.total++;
  statsWrite(dayNumber(t), cfg.todayCount > 255 ? 255 : cfg.todayCount);
  if (!statsWritePending) statsCompute();
}

void statsFlush(const struct tm &t) {
  if (!statsPending) return;
  stats.total += statsPending;
  statsPending = 0;
  statsWrite(dayNumber(t), cfg.todayCount > 255 ? 255 : cfg.todayCount);
  statsCompute();
}

void statsRollover(const struct tm &t) {
  statsWrite(dayNumber(t), cfg.todayCount > 255 ? 255 : cfg.todayCount);
  if (!statsWritePending) statsCompute();
}
