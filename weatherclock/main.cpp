// ---------- recovery: 3 short boots in a row ----------
// The device has no button: powering it on and off 3 times in a row (each time for under 30 s), or a
// firmware that crashes right at start-up, opens recovery mode (its own network, update without a password,
// factory settings). The counter lives in EEPROM, after the settings: it survives unplugging,
// unlike RTC memory. 30 s powered on resets the count.
const int BOOT_OFF = 400;
static_assert(sizeof(Settings) <= BOOT_OFF, "the settings would overlap the boot counter");
struct BootCount { uint32_t magic; uint8_t n; };
const uint32_t BOOT_MAGIC = 0x424F4F54;  // "BOOT"
uint8_t bootCount = 0;
bool recoveryMode = false;

// Last crash (exception or watchdog), so the panel can say why the clock restarted. It lives in EEPROM
// after the counter and is only written when the restart was abnormal: a normal boot uses no flash.
// "up" (seconds powered on before the crash) comes from RTC memory, which the callback below fills in on a crash.
struct CrashRec { uint32_t magic; uint8_t n, reason, exc, pad; uint32_t epc, vaddr, up; char ver[8]; };
const uint32_t CRASH_MAGIC = 0x43524153;  // "CRAS"
const int CRASH_OFF = BOOT_OFF + sizeof(BootCount);
// File storage mark for the 4M2M layout: "FS2M" = the LittleFS at this address was already formatted by us.
// Without it (first boot after coming from 4M3M or the original firmware) the contents there are garbage from the old
// layout and fsMount formats it; `pend` stays 1 until the panel confirms the backup was restored.
struct FsMark { uint32_t magic; uint8_t pend; };
const uint32_t FS_MAGIC = 0x46533241;  // "FS2A"
const int FS_OFF = CRASH_OFF + sizeof(CrashRec);
FsMark fsMark;
// Last router: channel and BSSID, so the next boot connects without scanning every channel (see connectStored).
// Only written when it changes (switching networks or the router changing channel): powering on uses no flash.
struct WifiHint { uint32_t magic; uint32_t ssid; uint8_t bssid[6]; uint8_t chan, pad; };
const uint32_t WIFI_MAGIC = 0x57494648;  // "WIFH"
const int WIFIH_OFF = FS_OFF + sizeof(FsMark);
const int EE_SIZE = WIFIH_OFF + sizeof(WifiHint);
static_assert(sizeof(WifiHint) == 16, "the Wi-Fi record changed size");
static_assert(sizeof(CrashRec) == 28, "the crash record changed size");
static_assert(sizeof(FW_VERSION) <= sizeof(CrashRec::ver), "the version does not fit in the crash record");
const uint32_t CRASH_RTC_TAG = 0x55505453;  // "UPTS"
// User RTC memory: blocks 0-31 (128 bytes) belong to the command the update leaves for the eboot
// (Updater, eboot_command at 0x60001200). Writing there between the end of the update and the restart corrupts the
// command, and the eboot boots the old version (that's what 1.23.2 did when saving the time). Our data: from 32 on.
const uint32_t RTC_CRASH_BLOCK = 32;  // 2 blocks: mark and seconds powered on
CrashRec crashRec;  // magic != CRASH_MAGIC: no crash stored

// runs on a crash (the core calls it in place of the extra notice): records how long it had been on
extern "C" void custom_crash_callback(struct rst_info *, uint32_t, uint32_t) {
  uint32_t v[2] = {CRASH_RTC_TAG, millis() / 1000};
  ESP.rtcUserMemoryWrite(RTC_CRASH_BLOCK, v, sizeof v);
}

void crashLoad() {
  EEPROM.get(CRASH_OFF, crashRec);
  if (crashRec.magic != CRASH_MAGIC) crashRec.magic = 0;
  const rst_info *r = ESP.getResetInfoPtr();
  if (!r || !(r->reason == REASON_WDT_RST || r->reason == REASON_EXCEPTION_RST || r->reason == REASON_SOFT_WDT_RST)) return;
  uint32_t v[2] = {0, 0};
  ESP.rtcUserMemoryRead(RTC_CRASH_BLOCK, v, sizeof v);
  uint8_t n = crashRec.magic ? crashRec.n : 0;
  crashRec = {CRASH_MAGIC, (uint8_t)(n < 255 ? n + 1 : n), (uint8_t)r->reason, (uint8_t)r->exccause, 0,
              r->epc1, r->excvaddr, v[0] == CRASH_RTC_TAG ? v[1] : 0, {}};
  strlcpy(crashRec.ver, FW_VERSION, sizeof crashRec.ver);
  EEPROM.put(CRASH_OFF, crashRec);
  EEPROM.commit();
}

void setBootCount(uint8_t n) {
  BootCount b = {BOOT_MAGIC, n};
  EEPROM.put(BOOT_OFF, b);
  EEPROM.commit();
  bootCount = n;
}

// requested restart (Wi-Fi, update...): doesn't count as a short boot
void rtcTimeSave();
void safeRestart() {
  if (bootCount) setBootCount(0);
  rtcTimeSave();  // the time survives the restart (RTC memory): the face comes back with it
  ESP.restart();
}

void loadSettings() {
  EEPROM.begin(EE_SIZE);
  EEPROM.get(0, cfg);
  if (cfg.magic == SETTINGS_MAGIC_V3) {
    // v3 -> v4: keeps everything, fills in the new fields and remaps the themes
    // (v3: 0 digital, 1 analog, 2 weather; v4: 0 matrix, 1 scene, 2 analog, 3 weather)
    const uint8_t themeMap[3] = {THEME_MATRIX, THEME_ANALOG, THEME_WEATHER};
    cfg.theme = cfg.theme < 3 ? themeMap[cfg.theme] : THEME_MATRIX;
    cfg.bgr = 0;
    cfg.invert = 1;
    cfg.flip = 0;
    cfg.dailyGoal = 8;
    cfg.activity = ACT_READ;
    cfg.magic = SETTINGS_MAGIC;
  } else if (cfg.magic != SETTINGS_MAGIC) {
    defaultSettings();
  }
  cfg.facePkg[sizeof(cfg.facePkg) - 1] = 0;
  for (char *p = cfg.facePkg; *p; p++)  // invalid id (old memory): no pack
    if (!((*p >= 'a' && *p <= 'z') || (*p >= '0' && *p <= '9') || *p == '-' || *p == '_')) {
      cfg.facePkg[0] = 0;
      break;
    }
  if (cfg.theme >= THEME_COUNT && !(cfg.theme == THEME_PACK && cfg.facePkg[0])) cfg.theme = THEME_MATRIX;
  if (!cfg.dailyGoal) cfg.dailyGoal = 8;
  if (cfg.activity >= ACT_COUNT) cfg.activity = ACT_READ;
  if (cfg.lang > 2) cfg.lang = 1;
  if (cfg.nightSun > 1) cfg.nightSun = 0;
  if (cfg.rotMin > 240) cfg.rotMin = 0;
  if (cfg.alexa > 1) cfg.alexa = 1;  // memory of old units (0xFF): on
  if (cfg.fahr > 1) cfg.fahr = 0;
  if (cfg.rainAlert > 1) cfg.rainAlert = 1;
  if (cfg.beta > 1) cfg.beta = 0;
  cfg.spi80 = 0;  // anyone who switched it on in the test goes back to 40 MHz
  {
    bool ok = memchr(cfg.devName, 0, sizeof cfg.devName) != nullptr;
    for (const char *c = cfg.devName; ok && *c; c++) ok = *c >= 0x20 && *c < 0x7F && *c != '"' && *c != '\\';
    if (!ok) cfg.devName[0] = 0;
  }
  if (!(fabsf(cfg.lat) <= 90 && fabsf(cfg.lon) <= 180)) cfg.lat = cfg.lon = 0;  // garbage or NaN would overflow String(float)
  // password for the clock's networks: 8 letters/digits without the easily confused ones, drawn by the chip's generator
  // the first time (or if the memory holds garbage) and shown on screen while the network is up
  static const char AP_CHARS[] = "abcdefghjkmnpqrstuvwxyz23456789";
  // VCOM: only the value the user calibrated (with the mark) is kept; garbage from old memory, 1.16.0
  // (mark 0x5A) and anyone who never calibrated follow the current default
  if (cfg.vcom > 0x3F || cfg.vcomChk != (cfg.vcom ^ 0xDA)) {
    cfg.vcom = UI_VCOM_DEFAULT;
    cfg.vcomChk = 0;
  }
  bool apOk = strnlen(cfg.apPass, sizeof cfg.apPass) == 8;
  for (int i = 0; apOk && i < 8; i++) apOk = strchr(AP_CHARS, cfg.apPass[i]) != nullptr;
  if (!apOk) {
    for (int i = 0; i < 8; i++) cfg.apPass[i] = AP_CHARS[ESP.random() % (sizeof AP_CHARS - 1)];
    cfg.apPass[8] = 0;
    EEPROM.put(0, cfg);  // save right away (saveSettings comes further down)
    EEPROM.commit();
  }
  cfg.tz[sizeof(cfg.tz) - 1] = 0;
  cfg.otaPass[sizeof(cfg.otaPass) - 1] = 0;
  cfg.city[sizeof(cfg.city) - 1] = 0;
  if (cfg.albumDelay < 3) cfg.albumDelay = 3;
}

void saveSettings() {
  EEPROM.put(0, cfg);
  EEPROM.commit();
}

