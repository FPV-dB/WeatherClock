bool fsOk = false;

// The _FS_start symbol comes from the linker script of the chosen layout (eagle.flash.4m2m.ld: 0x40400000).
bool fsLayout2() { return (uint32_t)&_FS_start == 0x40400000; }

// Mounts LittleFS WITHOUT formatting needlessly: if it fails, the files stay intact. The exception is migrating from the
// 4M3M layout (LittleFS at 0x100000) to 4M2M (0x200000): on the first boot here, with no mark in
// EEPROM, what sits at 0x200000 is a piece of the old file system (or of the original firmware's
// storage), so it formats once, recreates the folders and sets `pend` so the panel offers to restore
// the backup. If the mark exists and mounting fails, it does NOT format (it could be something else): the panel shows the Format button.
void fsMount() {
  LittleFSConfig fcfg;
  fcfg.setAutoFormat(false);
  LittleFS.setConfig(fcfg);
  fsOk = LittleFS.begin();
  if (!fsLayout2()) return;
  EEPROM.get(FS_OFF, fsMark);
  if (fsMark.magic == FS_MAGIC) return;
  message("Weather Clock", tr("Reorganizando a memoria", "Reorganizing storage", "Reorganizando la memoria"), "...");
  if (fsOk) LittleFS.end();
  // Before formatting, it saves the history, rotation and notices, which are worth more than the space they take: on the first
  // boot the old LittleFS (4M3M, 0x100000-0x3FA000) is still intact, because the update only wrote below
  // 0x100000. That way anyone updating without the panel backup (e.g. straight from 1.23.1) doesn't lose their streak.
  struct Keep { const char *path; std::unique_ptr<uint8_t[]> data; size_t len; } keep[] = {
      {"/stats.bin", nullptr, 0}, {"/rotation.txt", nullptr, 0}, {"/hooks.txt", nullptr, 0}};
  {
    FS old(FSImplPtr(new littlefs_impl::LittleFSImpl(0x100000, 0x3FA000 - 0x100000, 256, 8192, 2)));
    if (old.begin()) {
      for (Keep &k : keep) {
        File f = old.open(k.path, "r");
        if (!f || !f.size() || f.size() > 2048) continue;
        k.data.reset(new (std::nothrow) uint8_t[f.size()]);
        if (k.data) k.len = f.read(k.data.get(), f.size());
      }
      old.end();
    }
  }
  fsOk = LittleFS.format() && LittleFS.begin();
  if (!fsOk) return;  // no mark: try again on the next boot
  LittleFS.mkdir("/image");
  LittleFS.mkdir("/gif");
  LittleFS.mkdir("/faces");
  for (Keep &k : keep) {
    if (!k.len) continue;
    File f = LittleFS.open(k.path, "w");
    if (f) f.write(k.data.get(), k.len);
  }
  fsMark = {FS_MAGIC, 1};
  EEPROM.put(FS_OFF, fsMark);
  EEPROM.commit();
}
